function  sim_ini(varargin)
%
% function SIM_INI(config)
% =======================
% 
% Parameter <config> must be one of the following
% 'PC'  : Simulation on single PC ( Offline, non Real-Time)
% 'HIL' : Simulation on Real-Time-Hardware, with ECU
% 'CPT' : Simulation in Real-Time-Hardware, without I/O connected
%
%
%
% this file contains the parameters necessary to  initialize the
% simulation
%
% AUTHOR(S): dSPACE GmbH
%
% VERSION  : 1.0
%
% MODIFICATION(S):
% -------------
%
%    NAME:     |   DATE:      |                 REMARKS:
%--------------------------------------------------------------------
%              |              |    
%              |              |  
%              |              |   
%

config = varargin{2};

% Check input parameter
if (nargin==0)
        fprintf('No simode defined ... ');
        error
        return
    
elseif ( (strcmp(config,'PC')  == 0) && (strcmp(config,'HIL') == 0) && (strcmp(config,'CPT') == 0) ) 
        fprintf('No simode defined ... ');
        error
        return
    
elseif ((strcmp(config,'PC')  == 1) || (strcmp(config,'CPT')  == 1) || (strcmp(config,'HIL')  == 1))
    
    % Get structures from workspace
    SIM = evalin('base','SIM;','[];');
    
    %--------------------------------------------------------------------------------
    
    if (strcmp(config,'PC')  == 1) 
        SIM.StepSize = struct(...
            'vComment','Bigger StepSize for offboard simulation',...
            'vUnit','[s]',...
            'v',0.001);
        
        SIM.nciout = struct(...
            'vComment','stepsize multiplicator for communication interval',...
            'vUnit','[-]',...
            'v',10);
        
        SIM.tend = struct(...
            'vComment','Simulation end time',...
            'vUnit','[s]',...
            'v',inf);
        
        SIM.tstart = struct(...
            'vComment','Simulation start time',...
            'vUnit','[s]',...
            'v',0);
        
        SIM.hcan = struct(...
            'vComment','Simulation StepSize CAN',...
            'vUnit','[s]',...
            'v',10 * SIM.StepSize.v);
        
        SIM.NumSamplesAnimation = struct(...
            'vComment','Number of time steps between updates and provision of animation data',...
            'vUnit','[-]',...
            'v',20);
        
        SIM.Sw_ModelDeskPlottingInterface = struct(...
            'vComment','Enables the ModelDesk Plotting interface in all SignalInterface subsystems',...
            'vUnit','[0Disabled|1Enabled]',...
            'v',1);
        
        SIM.Sw_ModelPortBlocks = struct(...
            'vComment','Enables all Model Port blocks in all Interface_In and SignlInterface subsystems',...
            'vUnit','[0Disabled|1Enabled]',...
            'v',1);
        
        SIM.Sw_AnimationInterface = struct(...
            'vComment','Enables Animation Interface',...
            'vUnit','[0Disabled|1Enabled]',...
            'v',1);
        
    elseif ( (strcmp(config,'HIL')  == 1) || (strcmp(config,'CPT') == 1 ) )
        SIM.StepSize = struct(...
            'vComment','Smaller StepSize for onboard simulation',...
            'vUnit','[s]',...
            'v',0.001);
        
        SIM.nciout = struct(...
            'vComment','StepSize multiplicator for communication interval',...
            'vUnit','[-]',...
            'v',10); 
        
        SIM.tend = struct(...
            'vComment','Simulation end time',...
            'vUnit','[s]',...
            'v',inf); 
        
        SIM.tstart = struct(...
            'vComment','Simulation start time',...
            'vUnit','[s]',...
            'v',0);
        
        SIM.hcan = struct(...
            'vComment','Simulation StepSize CAN',...
            'vUnit','[s]',...
            'v',10 * SIM.StepSize.v);
        
        SIM.NumSamplesAnimation = struct(...
            'vComment','Number of time steps between updates and provision of animation data',...
            'vUnit','[-]',...
            'v',20);
        
        SIM.Sw_ModelDeskPlottingInterface = struct(...
            'vComment','Enables the ModelDesk Plotting interface in all SignalInterface subsystems',...
            'vUnit','[0Disabled|1Enabled]',...
            'v',1);
        
        SIM.Sw_ModelPortBlocks = struct(...
            'vComment','Enables all Model Port blocks in all Interface_In and SignlInterface subsystems',...
            'vUnit','[0Disabled|1Enabled]',...
            'v',1);
        
        SIM.Sw_AnimationInterface = struct(...
            'vComment','Enables Animation Interface',...
            'vUnit','[0Disabled|1Enabled]',...
            'v',1);
        
    end
    
    % Write structures back to workspace
    assignin('base','SIM',SIM);
    
    % Get structures from workspace
    MDL = evalin('base','MDL;','[];');
    
    % Brake hydraulics upsampling factor for stabilisation
    MDL.BrkHyd.UpSampleFaktor = struct(...
        'Comment','Upsampling factor for stabilisation via for-loop [-]',...
        'Origin','Default',...
        'vName','UpSampleFactor',...
        'vUnit','[-]',...
        'v',10);
    
    % Write structures back to workspace
    assignin('base','MDL',MDL);
    
end