function input = make_input(plan)
%MAKE_INPUT Bind every run variable explicitly; never assign the base workspace.
input = Simulink.SimulationInput(plan.options.Model);
for index = 1:height(plan.bindings)
    name = plan.bindings.name(index);
    workspace = plan.bindings.workspace(index);
    assert(isfield(plan.variables,name),'Missing binding value: %s',name);
    input = input.setVariable(name,plan.variables.(name),Workspace=workspace);
end
input = input.setModelParameter( ...
    'SolverType','Fixed-step','Solver','ode4', ...
    'FixedStep',sprintf('%.17g',plan.plant_step_s), ...
    'StopTime',sprintf('%.17g',plan.options.StopTime), ...
    'SimulationMode','normal','SignalLogging','on', ...
    'SignalLoggingName','logsout','ReturnWorkspaceOutputs','on', ...
    'CaptureErrors','on');
end
