function records = provenance(plan)
%PROVENANCE Hash and archive models, dictionaries, sources and selected build.
root = char(plan.options.Root);
entries = [dir(fullfile(root,'models','**','*.slx')); ...
    dir(fullfile(root,'models','**','*.sldd')); ...
    dir(fullfile(root,'src','**','*.m')); ...
    dir(fullfile(root,'config','**','*.m')); ...
    dir(fullfile(root,'scripts','**','*.m')); ...
    dir(fullfile(root,'experiments','**','*.m')); ...
    dir(fullfile(root,'dependencies','acados_v054_compat','**','*.*'))];
build = char(plan.options.BuildDirectory);
if ~isempty(build)
    assert(isfolder(build),'Selected solver build does not exist.');
    buildEntries = [dir(fullfile(build,'**','*.json')); ...
        dir(fullfile(build,'**','*.c'));dir(fullfile(build,'**','*.h')); ...
        dir(fullfile(build,'**','*.slx'));dir(fullfile(build,'**','*.m')); ...
        dir(fullfile(build,'**',['*.',mexext]))];
    entries = [entries;buildEntries];
end
paths = string(fullfile({entries(~[entries.isdir]).folder}, ...
    {entries(~[entries.isdir]).name})).';
paths = unique([paths;string(plan.provenance_files(:))]);
records = struct('path',{},'sha256',{});
for index = 1:numel(paths)
    records(index).path = paths(index);
    records(index).sha256 = ecu.simulation.file_hash(char(paths(index)));
end
end
