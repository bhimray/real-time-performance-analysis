function laneData = load_lane_data(matFile)
%LOAD_LANE_DATA Load and validate a saved road/reference before a run.
%
%   Load once outside the timed controller loop. Pass the returned structure
%   as the optional seventh argument of PREPARE_HORIZON.
%   MAT preserves scenario/vehicle metadata that the numeric CSV omits.

assert(isfile(matFile), ...
    'ecu:LaneFileMissing', ...
    'Lane MAT file does not exist: %s', matFile);

loaded = load(matFile, 'laneData');

assert(isfield(loaded, 'laneData'), ...
    'ecu:LaneFileFormat', ...
    'MAT file must contain a laneData structure.');

laneData = loaded.laneData;
% Normalize legacy labels without rewriting the saved scenario file.
laneData.instance = ecu.scenario.normalize_obstacle_names(laneData.instance);

requiredGroups = {
    'schema_version', 'instance', 'vehicle', ...
    'lanes', 'reference', 'lookup_table'
};

for group = 1:numel(requiredGroups)
    assert(isfield(laneData, requiredGroups{group}), ...
        'ecu:LaneFileFormat', ...
        'Saved lane data are missing %s.', requiredGroups{group});
end

assert(laneData.schema_version == 1, ...
    'ecu:LaneFileVersion', ...
    'Unsupported lane-data schema.');

station = laneData.reference.station_m;

validateattributes(station, {'double'}, ...
    {'column', 'real', 'finite', 'nonempty'});

assert(numel(station) >= 2 && all(diff(station) > 0), ...
    'ecu:LaneLookupStations', ...
    'Saved stations must be strictly increasing.');

requiredFields = {
    'X_m', 'Y_m', 'heading_rad', 'curvature_per_m', ...
    'psi_pvr', 'dpsi_pr', 'dpsi_pvr', 'ddpsi_pr', 'ddpsi_pvr', ...
    'vr', 'dvr', 'emin', 'emax'
};

for field = 1:numel(requiredFields)
    name = requiredFields{field};

    assert(isfield(laneData.reference, name), ...
        'ecu:LaneFileFormat', ...
        'Saved reference is missing %s.', name);

    validateattributes(laneData.reference.(name), {'double'}, ...
        {'size', [numel(station), 1], 'real', 'finite'});
end

assert(istable(laneData.lookup_table) && ...
    height(laneData.lookup_table) == numel(station), ...
    'ecu:LaneFileFormat', ...
    'Saved lookup table must have one row per station.');

assert(all(laneData.reference.emin < laneData.reference.emax), ...
    'ecu:LaneFileFormat', ...
    'Saved controller bounds are inconsistent.');

end

